// Turns tokens/tokens.json (the same values as the Figma variables) into CSS custom properties.
// Figma name `status/warning/fg` becomes `--status-warning-fg`, so names match across design and code.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'));
const cssName = (name) => '--' + name.replace(/\//g, '-');

function hexToRgba(hex, alpha) {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

const lines = [];
for (const [name, hex] of Object.entries(tokens.primitives)) lines.push(`  ${cssName(name)}: ${hex};`);
for (const [name, value] of Object.entries(tokens.tokens)) {
  const css = typeof value === 'string'
    ? `var(${cssName(value.slice(1, -1))})`
    : hexToRgba(value.hex, value.alpha);
  lines.push(`  ${cssName(name)}: ${css};`);
}
for (const [name, px] of Object.entries(tokens.dimensions)) lines.push(`  ${cssName(name)}: ${px}px;`);

writeFileSync(
  new URL('../src/tokens.css', import.meta.url),
  `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`,
);
console.log(`src/tokens.css: ${lines.length} custom properties`);
